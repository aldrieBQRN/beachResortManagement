    private void loadUserDetails() {
 
        try {
            
            String sql = "SELECT full_name, phone, email FROM user_details WHERE user_id = ?";
            
            pst = con.prepareStatement(sql);
            pst.setInt(1, userId);
            try (ResultSet rs = pst.executeQuery()) {
                if (rs.next()) {
                    nameField.setText(rs.getString("full_name"));
                    phoneField.setText(rs.getString("phone"));
                    emailField.setText(rs.getString("email"));
                    
                } else {
                    JOptionPane.showMessageDialog(this, "User not found");
                }
            }
        }   catch (SQLException ex) {
            java.util.logging.Logger.getLogger(guestProfile.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        }
  
                
    }
    
private void updateUserDetails() {
        try {
            // Get field values
            String fullName = nameField.getText().trim();
            String phone = phoneField.getText().trim();
            String email = emailField.getText().trim();
            
            // Validation checks
            if (fullName.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Full name cannot be empty", "Validation Error", JOptionPane.ERROR_MESSAGE);
                nameField.requestFocus();
                return;
            }
            
            if (!fullName.matches("[a-zA-Z ]{3,}")) {
                JOptionPane.showMessageDialog(this, "Full name must contain only letters and spaces (min 3 characters)",
                        "Validation Error", JOptionPane.ERROR_MESSAGE);
                nameField.requestFocus();
                return;
            }
            
            if (phone.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Phone number cannot be empty", "Validation Error", JOptionPane.ERROR_MESSAGE);
                phoneField.requestFocus();
                return;
            }
            
            if (!phone.matches("\\d{10,15}")) {
                JOptionPane.showMessageDialog(this, "Phone number must be 10-15 digits", "Validation Error", JOptionPane.ERROR_MESSAGE);
                phoneField.requestFocus();
                return;
            }
            
            if (email.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Email cannot be empty", "Validation Error", JOptionPane.ERROR_MESSAGE);
                emailField.requestFocus();
                return;
            }
            
            if (!email.matches("^[\\w-.]+@([\\w-]+\\.)+[\\w-]{2,4}$")) {
                JOptionPane.showMessageDialog(this, "Please enter a valid email address",
                        "Validation Error", JOptionPane.ERROR_MESSAGE);
                emailField.requestFocus();
                return;
            }
            
            // If all validations pass, proceed with database update
            
            String sql = "UPDATE user_details SET full_name = ?, phone = ?, email = ? WHERE user_id = ?";
            pst = con.prepareStatement(sql);
            pst.setString(1, fullName);
            pst.setString(2, phone);
            pst.setString(3, email);
            pst.setInt(4, userId);
            
            int rowsAffected = pst.executeUpdate();
            if (rowsAffected > 0) {
                JOptionPane.showMessageDialog(this, "Profile updated successfully",
                        "Success", JOptionPane.INFORMATION_MESSAGE);
            } else {
                JOptionPane.showMessageDialog(this, "No changes made to profile",
                        "Information", JOptionPane.INFORMATION_MESSAGE);
            }
        } catch (SQLException ex) {
            java.util.logging.Logger.getLogger(guestProfile.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        }

}


