    private void rSButtonHover2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_rSButtonHover2ActionPerformed

    try {
        InputStream is = null;
        PreparedStatement pst = null;
        
        // Get input values
        String boatNumber = (String) cmbBoatNumbers.getSelectedItem();
        String boatName = txtBoatName.getText().trim();
        String description = txtDescription.getText().trim();
        String tourPriceText = txtTourPrice.getText().trim();
        int capacity = (int) spinnerCapacity.getValue();
        
        // Validate required fields
        if (boatNumber == null || boatNumber.isEmpty() ||
                boatName.isEmpty() || description.isEmpty() || 
                tourPriceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "All fields must be filled!",
                    "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Validate tour price
        double tourPrice;
        try {
            tourPrice = Double.parseDouble(tourPriceText);
            if (tourPrice <= 0) {
                JOptionPane.showMessageDialog(this, "Tour price must be a positive number!",
                        "Validation Error", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid tour price format!",
                    "Input Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Validate capacity
        if (capacity <= 0) {
            JOptionPane.showMessageDialog(this, "Capacity must be greater than 0!",
                    "Validation Error", JOptionPane.ERROR_MESSAGE);
            return;
        }
        
        // Confirm update
        int confirm = JOptionPane.showConfirmDialog(this,
                "Are you sure you want to update the boat information?",
                "Confirm Update",
                JOptionPane.YES_NO_OPTION);
        
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }
        
        // Prepare image stream if path exists
        File f = null;
        if (path != null && !path.trim().isEmpty()) {
            f = new File(path);
            if (f.exists()) {
                try {
                    is = new FileInputStream(f);
                } catch (FileNotFoundException ex) {
                    java.util.logging.Logger.getLogger(adminUpdateBoat.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
                }
            }
        }
        
        // Prepare SQL query
        String sql;
        if (is != null) {
            sql = "UPDATE boat SET boat_name = ?, boat_image = ?, description = ?, " +
                    "capacity = ?, tour_price = ? WHERE boat_number = ?";
        } else {
            sql = "UPDATE boat SET boat_name = ?, description = ?, " +
                    "capacity = ?, tour_price = ? WHERE boat_number = ?";
        }
        
        // Execute update
        try {
            pst = con.prepareStatement(sql);
            
            if (is != null) {
                pst.setString(1, boatName);
                pst.setBinaryStream(2, is, (int)f.length());
                pst.setString(3, description);
                pst.setInt(4, capacity);
                pst.setDouble(5, tourPrice);
                pst.setString(6, boatNumber);
            } else {
                pst.setString(1, boatName);
                pst.setString(2, description);
                pst.setInt(3, capacity);
                pst.setDouble(4, tourPrice);
                pst.setString(5, boatNumber);
            }
            
            int rowsUpdated = pst.executeUpdate();
            
            if (rowsUpdated > 0) {
                JOptionPane.showMessageDialog(this, "Boat updated successfully!");
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Boat number not found or no changes made.",
                        "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException ex) {
            java.util.logging.Logger.getLogger(adminUpdateBoat.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        } finally {
            // Close resources
            if (is != null) {
                try {
                    is.close();
                } catch (IOException ex) {
                    java.util.logging.Logger.getLogger(adminUpdateBoat.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
                }
            }
            if (pst != null) {
                try {
                    pst.close();
                } catch (SQLException ex) {
                    java.util.logging.Logger.getLogger(adminUpdateBoat.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
                }
            }
        }
    } catch (Exception ex) {
        java.util.logging.Logger.getLogger(adminUpdateBoat.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
        JOptionPane.showMessageDialog(this, "An unexpected error occurred: " + ex.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
    }




    }//GEN-LAST:event_rSButtonHover2ActionPerformed

