    private void cmbBoatNumbersItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cmbBoatNumbersItemStateChanged
      try {
    // Only proceed if an item is selected and it's not the default empty value
    String selectedBoatNumber = (String) cmbBoatNumbers.getSelectedItem();

    // If no boat number is selected (empty or null), do nothing
    if (selectedBoatNumber == null || selectedBoatNumber.isEmpty() || selectedBoatNumber.equals("Select a Boat Number")) {
        return;
    }

    // Prepare the SQL query to fetch all boat details including image
    String sql = "SELECT boat_name, description, tour_price, capacity, boat_image FROM boat WHERE boat_number = ?";
    pst = con.prepareStatement(sql);
    pst.setString(1, selectedBoatNumber);

    // Execute the query
    rs = pst.executeQuery();

    // Check if the boat exists in the database
    if (rs.next()) {
        // Set the values of the form fields
        txtBoatName.setText(rs.getString("boat_name"));
        txtDescription.setText(rs.getString("description"));
        txtTourPrice.setText(String.format("%.2f", rs.getDouble("tour_price"))); // Format price
        spinnerCapacity.setValue(rs.getInt("capacity"));

        // Load and display the boat image
        loadBoatImage(rs.getBytes("boat_image"));
    } else {
        JOptionPane.showMessageDialog(this, "Boat not found in database", "Error", JOptionPane.WARNING_MESSAGE);
    }
} catch (SQLException ex) {
    java.util.logging.Logger.getLogger(adminUpdateBoat.class.getName()).log(java.util.logging.Level.SEVERE, null, ex);
}
    }//GEN-LAST:event_cmbBoatNumbersItemStateChanged

